/// A saved unit. password / private_key carry plaintext ONLY inside Rust
/// (right after a vault decrypt); listings sent to the webview have them
/// blanked.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SshServer {
    #[serde(default)]
    pub id: String,
    pub name: String,
    pub host: String,
    #[serde(default = "default_port")]
    pub port: u16,
    pub username: String,
    /// "password" | "key" (inline) | "cred" (a saved ssh_keys credential).
    #[serde(default = "default_auth")]
    pub auth: String,
    #[serde(default)]
    pub password: String,
    /// PEM/OpenSSH private key text (auth == "key").
    #[serde(default)]
    pub private_key: String,
    /// Id of a saved key credential (auth == "cred").
    #[serde(default)]
    pub key_id: String,
    /// Pinned host-key fingerprint ("SHA256:..."); empty = not seen yet.
    #[serde(default)]
    pub host_key: String,
    /// True in listings when a password is stored (the secret itself never
    /// leaves Rust) — lets the UI show which auth methods are configured.
    #[serde(default)]
    pub has_password: bool,
    /// Distribution detected on connect ("ubuntu", "fedora", "windows", …);
    /// empty = not detected yet. The UI maps it to a logo in /icons/os.
    #[serde(default)]
    pub os: String,
    /// Passphrase of the linked credential key — runtime-only (load_server
    /// fills it from ssh_keys); never persisted on the server row itself.
    #[serde(default)]
    pub key_passphrase: String,
}

/// A standalone private-key credential, reusable by several servers.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SshKey {
    #[serde(default)]
    pub id: String,
    pub name: String,
    /// Plaintext only inside Rust; blanked in listings.
    #[serde(default)]
    pub private_key: String,
    /// Plaintext only inside Rust; blanked in listings.
    #[serde(default)]
    pub passphrase: String,
    /// True in listings when a key body is stored.
    #[serde(default)]
    pub has_key: bool,
    /// Fingerprint of the stored key, for display (never the key itself).
    #[serde(default)]
    pub fingerprint: String,
    /// OpenSSH key comment; app-generated keys carry "Generated By Singularity".
    #[serde(default)]
    pub comment: String,
    /// The public half in authorized_keys form — safe to show/copy; the
    /// private body never leaves Rust.
    #[serde(default)]
    pub public_key: String,
}

